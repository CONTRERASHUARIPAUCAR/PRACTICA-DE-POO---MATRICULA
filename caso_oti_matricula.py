# REDISEÑO: para cada estudiante se decide si la beca va antes o despues de los recargos
class MatriculaCorregida(Matricula):
  def __init__(self, full_name):
    super().__init__(full_name)
    self.__extemporanea = "no"
    self.__desaprobatoria = "no"
    self.__beca = "no"
    self.__beca_primero = "despues"

  @property
  def extemporanea(self):
    return self.__extemporanea

  @property
  def desaprobatoria(self):
    return self.__desaprobatoria

  @property
  def beca(self):
    return self.__beca

  @property
  def beca_primero(self):
    return self.__beca_primero

  @extemporanea.setter
  def extemporanea(self, extemporanea):
    self.__extemporanea = extemporanea

  @desaprobatoria.setter
  def desaprobatoria(self, desaprobatoria):
    self.__desaprobatoria = desaprobatoria

  @beca.setter
  def beca(self, beca):
    self.__beca = beca

  @beca_primero.setter
  def beca_primero(self, beca_primero):
    self.__beca_primero = beca_primero

  def costo(self):
    monto = super().costo()
    if self.__beca == "si" and self.__beca_primero == "antes":
      monto = monto / 2
    if self.__extemporanea == "si":
      monto = monto + 15.00
    if self.__desaprobatoria == "si":
      monto = monto + 15.00
    if self.__beca == "si" and self.__beca_primero == "despues":
      monto = monto / 2
    return monto

  def information(self):
    super().information()
    print(f"Extemporanea: {self.__extemporanea}")
    print(f"Indice desaprobatorio: {self.__desaprobatoria}")
    print(f"Beca: {self.__beca}")
    print(f"Beca aplicada: {self.__beca_primero} de los recargos")



